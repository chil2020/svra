package io.svra.command;

/**
 * 完全相符的固定字串，直接對應到動作，<b>不經過 LLM</b>。
 *
 * <p>起因是圖文選單：按鈕送出的是<b>永遠一模一樣的字串</b>，
 * 而讓模型去理解一個我們自己寫死的字，本來就沒有道理。三個代價都是真的——
 * 慢（Ollama 一次呼叫）、不確定（同一句每次重新猜一次意圖），
 * 而且<b>打在瓶頸上</b>：Ollama 只有一份，這條路會跟語音抽取搶同一個推論資源。
 *
 * <p>🔴 <b>只認完全相符，刻意不做模糊比對。</b>「列出」「還有什麼」那類說法留給 LLM——
 * 在它旁邊再造一個意圖判斷器，兩邊會漸行漸遠，而不一致時很難查是哪一邊錯。
 * 完全相符沒有這個問題：它要嘛中，要嘛整句原封不動落回原本那條路。
 */
enum QuickCommand {

    /** 列出目前的項目。走既有的 LIST，只是跳過解析。 */
    LIST,

    /**
     * 回一份使用說明。
     *
     * <p>🔴 <b>它刻意不是 {@code NoteCommand.Action} 的成員。</b>那個 enum 是
     * <b>餵給 LLM 的動作清單</b>——多一個 HELP，模型就會開始在不該的時候回傳它，
     * 而使用者說「幫我刪掉第一筆」卻收到一份說明書，比解析失敗更糟。
     * 快速路徑排在解析之前，所以 LLM 的詞彙表一個字都不用動。
     */
    HELP;

    /**
     * 🔴 <b>這些字串同時存在於兩個地方</b>：這裡，以及 LINE 後台的圖文選單設定。
     * 選單是在後台建的（決策 33），所以那一份不在版控裡。
     *
     * <p>後台改了字而這裡沒跟著改，症狀<b>不是壞掉</b>——按鈕會靜靜地掉回 LLM 解析，
     * 多半仍然做對事，只是慢、而且偶爾解錯。<b>不會有人發現。</b>
     * 所以動這裡的字串時，後台要一起改。
     */
    static QuickCommand resolve(String text) {
        if (text == null) {
            return null;
        }
        // trim 是因為使用者手打時容易多一個空格；除此之外不做任何正規化——
        // 每多一種「也算相符」的寫法，就離「模糊比對」近一步。
        return switch (text.trim()) {
            case "列出行程" -> LIST;
            case "使用說明" -> HELP;
            default -> null;
        };
    }
}
