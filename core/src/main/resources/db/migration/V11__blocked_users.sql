-- 誰已經把這個官方帳號封鎖／刪除好友了。
--
-- 起因是開放給多人使用：單人的時候「使用者封鎖你」這件事沒有意義，
-- 因為那個使用者就是你。多人之後它每天都可能發生，而系統原本對它一無所知——
-- `unfollow` 事件跟貼圖、已讀一樣掉進「收得下但不處理」。
--
-- 記下來有兩個用途：
--   1. 不要再對他做事。他收不到，做了也是白做（LINE 對封鎖者的訊息不計費，
--      所以省的不是錢，是不要在 log 裡堆一堆註定沒有意義的推播）
--   2. 之後要清理資料時，這是唯一知道「這個人已經不在了」的地方
--
-- 為什麼是「封鎖清單」而不是「使用者表」：這個系統從來沒有註冊的概念，
-- 使用者是 webhook 帶進來的（notes.line_user_id）。憑空生一張使用者表，
-- 就得回答「什麼時候建立、誰負責維護」——而目前唯一需要的事實只有這一個。
-- 真的需要使用者表的那天（多租戶 OAuth）再建，那時它會有更多欄位要放。
CREATE TABLE blocked_users (
    line_user_id VARCHAR(64) PRIMARY KEY,
    blocked_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
