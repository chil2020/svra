-- 「occursAt 裡的時刻是使用者講的，還是規則補的」。
--
-- 起因：抽取的 prompt 從第一天就寫著「只講到日期沒講時間就用當天 09:00」。
-- 那條規則本身是對的——清單上總得印個時間——但它讓資料庫裡的 09:00 有了
-- 兩種完全不同的來源，而**存進來之後那兩者長得一模一樣**。
--
-- 在只有「推播成文字清單」這一個下游時，分不出來沒有代價。
-- 一旦要匯進 Google 行事曆就有了：使用者說的三點是 start.dateTime 的定時事件，
-- 規則補的九點該是 start.date 的全天事件。
--
-- 為什麼不用啟發法（「時間剛好是 09:00 就當全天」）：那會把真的約早上九點的
-- 會議默默變成全天事件，而且不會有任何警告。把「不知道」偽裝成「知道」，
-- 比誠實地多一個欄位糟得多——同一個判斷見決策 12。
--
-- 可為 NULL，而且 NULL 有意義：
--   true  = 使用者講了幾點
--   false = 只講了日期，時刻是補的
--   NULL  = 沒有 occursAt，或是 v8 之前的舊資料（那時沒有人記下這件事）
-- 舊資料一律留 NULL，不回填猜測值——回填就等於在資料庫裡寫下一個沒有人說過的事實。
ALTER TABLE note_items ADD COLUMN time_specified BOOLEAN;
